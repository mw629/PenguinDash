param (
    [string]$projectDir = ""
)

if ($projectDir) {
    $projectDir = $projectDir.Trim().TrimEnd('"', '\', '/')
}

if (-not $projectDir -or -not (Test-Path $projectDir)) {
    # スクリプトの3階層上（MatchaEngine/Network/Firebase から見てプロジェクトルート）
    $projectDir = (Resolve-Path "$PSScriptRoot\..\..\..").Path
}

$outputHeader = Join-Path $PSScriptRoot "EmbeddedEnv.h"
$envPath = Join-Path $projectDir "My.env"
if (-not (Test-Path $envPath)) {
    $envPath = Join-Path $projectDir ".env"
}

$hasData = $false
$byteList = @()
$mask = 0x5A

if (Test-Path $envPath) {
    # UTF-8 で My.env を読み込み
    $rawContent = [System.IO.File]::ReadAllText($envPath, [System.Text.Encoding]::UTF8)
    if (-not [string]::IsNullOrWhiteSpace($rawContent)) {
        $hasData = $true
        $bytes = [System.Text.Encoding]::UTF8.GetBytes($rawContent)
        foreach ($b in $bytes) {
            $byteList += ($b -bxor $mask)
        }
    }
}

# ヘッダーコードの生成
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("// Auto-generated by GenerateEmbeddedEnv.ps1. Do not edit manually.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("#include <string>")
[void]$sb.AppendLine("#include <cstdint>")
[void]$sb.AppendLine()
[void]$sb.AppendLine("namespace EmbeddedEnv {")

if ($hasData -and $byteList.Count -gt 0) {
    [void]$sb.AppendLine("inline bool HasEmbeddedData() {")
    [void]$sb.AppendLine("    return true;")
    [void]$sb.AppendLine("}")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("inline std::string GetEmbeddedEnvContent() {")
    [void]$sb.AppendLine("    static const uint8_t kMask = 0x$($mask.ToString('X2'));")
    [void]$sb.AppendLine("    static const uint8_t kData[] = {")

    # 16バイトごとに改行してコード整形
    $lineItems = @()
    for ($i = 0; $i -lt $byteList.Count; $i++) {
        $lineItems += "0x" + $byteList[$i].ToString("X2")
        if ($lineItems.Count -eq 16 -or $i -eq ($byteList.Count - 1)) {
            $comma = if ($i -eq ($byteList.Count - 1)) { "" } else { "," }
            [void]$sb.AppendLine("        " + ($lineItems -join ", ") + $comma)
            $lineItems = @()
        }
    }

    [void]$sb.AppendLine("    };")
    [void]$sb.AppendLine("    static const size_t kDataSize = sizeof(kData);")
    [void]$sb.AppendLine("    std::string result;")
    [void]$sb.AppendLine("    result.resize(kDataSize);")
    [void]$sb.AppendLine("    for (size_t i = 0; i < kDataSize; ++i) {")
    [void]$sb.AppendLine("        result[i] = static_cast<char>(kData[i] ^ kMask);")
    [void]$sb.AppendLine("    }")
    [void]$sb.AppendLine("    return result;")
    [void]$sb.AppendLine("}")
} else {
    [void]$sb.AppendLine("inline bool HasEmbeddedData() {")
    [void]$sb.AppendLine("    return false;")
    [void]$sb.AppendLine("}")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('inline std::string GetEmbeddedEnvContent() {')
    [void]$sb.AppendLine('    return "";')
    [void]$sb.AppendLine('}')
}

[void]$sb.AppendLine("} // namespace EmbeddedEnv")

$newContent = $sb.ToString()

# 既存ファイルと同一内容なら更新しない（不要なリビルド防止）
$needWrite = $true
if (Test-Path $outputHeader) {
    $existingContent = [System.IO.File]::ReadAllText($outputHeader, [System.Text.Encoding]::UTF8)
    if ($existingContent -eq $newContent) {
        $needWrite = $false
    }
}

if ($needWrite) {
    [System.IO.File]::WriteAllText($outputHeader, $newContent, [System.Text.Encoding]::UTF8)
    Write-Host "[GenerateEmbeddedEnv] Generated EmbeddedEnv.h (hasData = $hasData, bytes = $($byteList.Count))"
    # EnvLoader.cpp の更新日時を更新し、コンパイラが確実に再コンパイルするようにする
    $envLoaderCpp = Join-Path $PSScriptRoot "EnvLoader.cpp"
    if (Test-Path $envLoaderCpp) {
        (Get-Item $envLoaderCpp).LastWriteTime = Get-Date
    }
} else {
    Write-Host "[GenerateEmbeddedEnv] EmbeddedEnv.h is up to date."
}

exit 0
